/**
 * Step 6 self-hosted path. Reads the provider's approved listing (from the
 * `endpoints` row Step 4 created/updated) and builds a downloadable ZIP —
 * never touches the provider's actual dataset (CLAUDE.md P1), only the
 * metadata they already approved.
 */
export async function generateEndpointPackage(providerId: string, sessionToken: string): Promise<GeneratePackageResult> {
  try {
    await validateOnboardingSession(providerId, sessionToken);
  } catch (err) {
    return { success: false, error: err instanceof InvalidOnboardingSessionError ? err.message : "Invalid session." };
  }

  const supabase = createServiceClient();

  const { data: provider, error: providerError } = await supabase
    .from("providers")
    .select("institution_name, country")
    .eq("id", providerId)
    .maybeSingle();

  if (providerError || !provider) {
    console.error("Package generation — provider lookup failed:", providerError);
    return { success: false, error: "Could not find your provider record." };
  }

  const { data: endpoint, error: endpointError } = await supabase
    .from("endpoints")
    .select("title, description, data_category, data_sub_category, geography_region, pricing_tiers")
    .eq("provider_id", providerId)
    .order("created_at", { ascending: false })
    .limit(1)
    .maybeSingle();

  if (endpointError || !endpoint) {
    console.error("Package generation — endpoint lookup failed:", endpointError);
    return { success: false, error: "Could not find your approved listing. Please complete Step 4 (Review) first." };
  }

  const pricingTiers = (endpoint.pricing_tiers ?? []) as PricingTier[];
  const providerSlug = slugify(provider.institution_name as string);

  const zip = new JSZip();
  zip.file(
    "index.ts",
    buildIndexTs({
      title: endpoint.title as string,
      description: endpoint.description as string,
      institutionName: provider.institution_name as string,
      country: provider.country as string,
      category: endpoint.data_category as string,
      subCategory: (endpoint.data_sub_category as string | null) ?? null,
      pricingTiers,
    }),
  );
  zip.file("package.json", buildPackageJson(providerSlug));
  zip.file("README.md", buildReadme({ institutionName: provider.institution_name as string, title: endpoint.title as string }));
  zip.file(".env.example", buildEnvExample());
  zip.file(
    "pdp-schema.json",
    buildPdpSchema({
      title: endpoint.title as string,
      description: endpoint.description as string,
      category: endpoint.data_category as string,
      subCategory: (endpoint.data_sub_category as string | null) ?? null,
      geography: (endpoint.geography_region as string | null) ?? null,
      pricingTiers,
    }),
  );

  const base64Zip = await zip.generateAsync({ type: "base64" });

  return { success: true, filename: `pdc-endpoint-${providerSlug}.zip`, base64Zip };
}
